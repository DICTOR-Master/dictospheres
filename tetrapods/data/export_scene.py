# The Tannowa scene for "Drop us a tetrapod" (DICTO, 2026-10-14): a 270 x 180 crop (about 1.07 x 0.71 km at 3.95 m) of the GSI
# elevation grid round Tannowa harbour. Inland gaps (ponds) take their neighbours' lowest height; the sea floor, which the land data does
# not cover, deepens gently away from the shore (0.6 m at the shore, 4 cm per metre, to 10 m). Heights in decimetres, base64 Int16.
# Writes scene.js. Source: 国土地理院 (GSI Japan) elevation tiles. DICTO · dictospheres.com
import base64, json, os
import numpy as np
from scipy import ndimage
HERE = os.path.dirname(os.path.abspath(__file__))
d = np.load(os.path.join(HERE, 'coast.npz')); H = d['h']; px = float(d['px'])
cx, cy, w, h = 1460, 240, 270, 180
C = H[cy - h // 2:cy + h // 2, cx - w // 2:cx + w // 2].astype(np.float64)
nan = ~np.isfinite(C)
lab, n = ndimage.label(nan)
sea_lab = set(np.unique(lab[0, :])) | set(np.unique(lab[:, 0])) | set(np.unique(lab[:, -1]))
sea_lab.discard(0)
sea = np.isin(lab, list(sea_lab))
inland = nan & ~sea
if inland.any():
    fill = ndimage.grey_erosion(np.where(nan, np.inf, C), size=5)
    C[inland] = np.where(np.isfinite(fill[inland]), fill[inland], 0.5)
dist = ndimage.distance_transform_edt(sea) * px
C[sea] = -np.minimum(10, 0.6 + dist[sea] * 0.04)
q = np.clip(np.round(C * 10), -32000, 32000).astype('<i2')
js = ('// Generated by tetrapods/data/export_scene.py. Terrain: 国土地理院 (GSI Japan) elevation tiles, Tannowa, Misaki, Osaka.\n'
      f'window.TANNOWA = {json.dumps(dict(w=w, h=h, cell=round(px, 4), heights=base64.b64encode(q.tobytes()).decode()))};\n')
open(os.path.join(HERE, '..', 'scene.js'), 'w').write(js)
print('scene', w, 'x', h, 'cell', round(px, 2), 'm; land', round(float((C > 0).mean()), 2), 'kB', len(js) // 1024)
