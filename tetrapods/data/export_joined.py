# The joined coast for "Drop us a tetrapod" (DICTO, 2026-10-14): three real stretches of the Misaki coast, southern Osaka Bay, from the GSI
# elevation grid (coast.npz, 3.95 m cells), set side by side west to east and blended across 50-cell seams, each piece moved up or down so its shore runs across the scene at the same depth: Fuke harbour, the wooded
# headland, and Tannowa harbour. Each piece is 220 x 180 cells (0.87 x 0.71 km) with the sea to the north. Inland gaps (ponds) take their
# neighbours' lowest height; the sea floor, which the land data does not cover, stays shallow far out (0.3 m at the shore, 1 cm per
# metre, to 3.5 m); the coastline is smoothed in a narrow band so it is not stair-stepped. Heights in decimetres, base64 Int16.
# Writes scene.js. Source: 国土地理院 (GSI Japan) elevation tiles. DICTO · dictospheres.com
import base64, json, os
import numpy as np
from scipy import ndimage
HERE = os.path.dirname(os.path.abspath(__file__))
d = np.load(os.path.join(HERE, 'coast.npz')); H = d['h']; px = float(d['px'])
PIECES = [('Fuke', 330, 640), ('the headland', 980, 430), ('Tannowa', 1460, 240)]   # centre column, centre row in coast.npz
w, h, SEAM, SEA = 220, 180, 50, -0.5

def piece(cx, cy):
    C = H[cy - h // 2:cy + h // 2, cx - w // 2:cx + w // 2].astype(np.float64)
    nan = ~np.isfinite(C)
    lab, _ = ndimage.label(nan)
    edge = set(np.unique(lab[0, :])) | set(np.unique(lab[:, 0])) | set(np.unique(lab[:, -1])); edge.discard(0)
    sea = np.isin(lab, list(edge)); inland = nan & ~sea
    if inland.any():
        fill = ndimage.grey_erosion(np.where(nan, np.inf, C), size=5)
        C[inland] = np.where(np.isfinite(fill[inland]), fill[inland], 0.5)
    C[sea] = SEA
    return C

# line the pieces up: move each piece up or down (its crop row) so its shore runs across the scene at the same depth, sea in front
# (north) and land behind, so the shore runs on across the seams; the blend smooths what is left
SHORE = 72   # target shore row
def shoreline(C):   # first land row from the sea side, per column
    return np.array([int(np.argmax(C[:, c] > 0)) if (C[:, c] > 0).any() else h for c in range(C.shape[1])])
def place(cx, cy):
    ok = [dy for dy in range(-200, 201, 2) if 0 <= cy + dy - h // 2 and cy + dy + h // 2 <= H.shape[0]]
    def cost(dy):
        sl = shoreline(piece(cx, cy + dy)); edges = np.r_[sl[:SEAM], sl[-SEAM:]]
        return np.abs(sl - SHORE).mean() + 2 * np.abs(edges - SHORE).mean()
    dy = min(ok, key=cost); print('row shift', dy, 'cost', round(cost(dy), 1)); return piece(cx, cy + dy)
# search the whole fetched coast for windows whose shore runs west-east at the target depth, then keep the best three that do not
# overlap, in west-to-east order (the stretches named above were the first choice; this finds ones that join cleanly)
def cost_at(cx, cy):
    sl = shoreline(piece(cx, cy)); edges = np.r_[sl[:SEAM], sl[-SEAM:]]
    return np.abs(sl - SHORE).mean() + 2 * np.abs(edges - SHORE).mean()
cands = []
for cx in range(w // 2, H.shape[1] - w // 2, 20):
    for cy in range(h // 2, H.shape[0] - h // 2, 10):
        C = H[cy - h // 2:cy + h // 2, cx - w // 2:cx + w // 2]
        if not 0.2 < np.isnan(C).mean() < 0.6: continue
        cands.append((cost_at(cx, cy), cx, cy))
cands.sort(); chosen = []
for c, cx, cy in cands:
    if all(abs(cx - ox) >= w for _, ox, _ in chosen): chosen.append((c, cx, cy))
    if len(chosen) == 3: break
chosen.sort(key=lambda t: t[1])
for c, cx, cy in chosen: print('window centre col', cx, 'row', cy, 'cost', round(c, 1), '~ lon', round(135.110 + 0.090 * cx / H.shape[1], 4))
PIECES = [(f'col {cx}', cx, cy) for _, cx, cy in chosen]
parts = [piece(cx, cy) for _, cx, cy in PIECES]

W = len(parts) * w - (len(parts) - 1) * SEAM
J = np.zeros((h, W))
x0 = 0
for k, P in enumerate(parts):
    if k == 0: J[:, :w] = P
    else:
        t = np.linspace(0, 1, SEAM); s = t * t * (3 - 2 * t)
        J[:, x0:x0 + SEAM] = J[:, x0:x0 + SEAM] * (1 - s) + P[:, :SEAM] * s
        J[:, x0 + SEAM:x0 + w] = P[:, SEAM:]
    x0 += w - SEAM
sea = J < 0
lab, _ = ndimage.label(sea)
edge = set(np.unique(lab[0, :])) | set(np.unique(lab[:, 0])) | set(np.unique(lab[:, -1])); edge.discard(0)
pond = sea & ~np.isin(lab, list(edge)); J[pond] = 0.3          # little pools left by the blend become low ground
sea = np.isin(lab, list(edge))
dist = ndimage.distance_transform_edt(sea) * px
J[sea] = -np.minimum(3.5, 0.3 + dist[sea] * 0.01)
band = (ndimage.distance_transform_edt(~sea) * px < 14) | ((dist < 14) & sea)
J = np.where(band, ndimage.gaussian_filter(J, 1.4), J)
q = np.clip(np.round(J * 10), -32000, 32000).astype('<i2')
names = ', '.join(n for n, _, _ in PIECES)
js = (f'// Generated by tetrapods/data/export_joined.py. Terrain: 国土地理院 (GSI Japan) elevation tiles; {names} (Misaki, Osaka), joined.\n'
      f'window.COAST = {json.dumps(dict(w=W, h=h, cell=round(px, 4), heights=base64.b64encode(q.tobytes()).decode()))};\n')
open(os.path.join(HERE, '..', 'scene.js'), 'w').write(js)
print('joined', W, 'x', h, '=', round(W * px / 1000, 2), 'x', round(h * px / 1000, 2), 'km; land', round(float((J > 0).mean()), 2), 'kB', len(js) // 1024)
# a quick shaded check image
import PIL.Image as I
img = np.zeros((h, W, 3), np.uint8); L = J > 0
gy, gx = np.gradient(J); sh = np.clip(0.75 + (gx - gy) * 0.6, 0, 1)
img[L] = (np.stack([120 * sh, 150 * sh, 90 * sh], -1)[L]).astype(np.uint8)
img[~L] = (np.stack([60 + 0 * J, 120 + 10 * J, 150 + 10 * J], -1)[~L]).clip(0, 255).astype(np.uint8)
I.fromarray(img).resize((W * 2, h * 2)).save(os.path.join(HERE, 'joined-check.png'))
